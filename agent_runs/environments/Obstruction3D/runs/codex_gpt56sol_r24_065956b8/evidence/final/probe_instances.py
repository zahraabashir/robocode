"""Exploration-only probes for Obstruction3DEnv."""
import argparse
import json
import numpy as np
from scipy.optimize import least_squares
from scipy.spatial.transform import Rotation

from env_client import make_env


ORIGINS = [([0, 0, .15643], [np.pi, 0, 0]), ([0, .005375, -.12838], [np.pi/2, 0, 0]),
           ([0, -.21038, -.006375], [-np.pi/2, 0, 0]), ([0, .006375, -.21038], [np.pi/2, 0, 0]),
           ([0, -.20843, -.006375], [-np.pi/2, 0, 0]), ([0, .00017505, -.10593], [np.pi/2, 0, 0]),
           ([0, -.10593, -.00017505], [-np.pi/2, 0, 0])]
QHOME = np.array([0, -.35, -np.pi, -2.5, 0, -.87, np.pi/2])


def fk(q):
    t = np.eye(4)
    for qi, (xyz, rpy) in zip(q, ORIGINS):
        a = np.eye(4); a[:3, :3] = Rotation.from_euler("xyz", rpy).as_matrix(); a[:3, 3] = xyz
        z = np.eye(4); z[:3, :3] = Rotation.from_euler("z", qi).as_matrix()
        t = t @ a @ z
    a = np.eye(4); a[:3, :3] = Rotation.from_euler("x", np.pi).as_matrix(); a[:3, 3] = [0, 0, -.061525]
    return t @ a


def ik(xyz, off=.12):
    def fun(q):
        t = fk(q); grasp = t[:3, 3] + off * t[:3, 2]
        return np.r_[5 * (grasp - xyz), t[:2, 2], .15 * (q - QHOME)]
    return least_squares(fun, QHOME, max_nfev=300).x


def ik_fixed(xyz, seed, rotation, off=.16):
    def fun(q):
        t = fk(q); grasp = t[:3, 3] + off * t[:3, 2]
        dr = Rotation.from_matrix(rotation.T @ t[:3, :3]).as_rotvec()
        return np.r_[8 * (grasp - xyz), 2 * dr, .02 * (q - seed)]
    return least_squares(fun, seed, max_nfev=500).x


def snapshot(state):
    rows = {}
    for name in state.get_object_names():
        obj = state.get_object_from_name(name)
        vals = {}
        for feat in (
            "pose_x", "pose_y", "pose_z", "pose_qx", "pose_qy", "pose_qz", "pose_qw",
            "half_extent_x", "half_extent_y", "half_extent_z", "grasp_active", "object_type",
            "pos_base_x", "pos_base_y", "pos_base_rot", "joint_1", "joint_2", "joint_3",
            "joint_4", "joint_5", "joint_6", "joint_7", "finger_state", "grasp_tf_x",
            "grasp_tf_y", "grasp_tf_z",
        ):
            try:
                vals[feat] = float(state.get(obj, feat))
            except Exception:
                pass
        rows[name] = vals
    return rows


def resets(n):
    env = make_env()
    records = []
    try:
        for seed in range(n):
            s, info = env.reset(seed=seed)
            rows = snapshot(s)
            rec = {"seed": seed, "names": list(rows), "info": info}
            for name, vals in rows.items():
                rec[name] = vals
            records.append(rec)
    finally:
        env.close()
    print(json.dumps(records, separators=(",", ":")))


def effects(seed, index, value, steps):
    env = make_env()
    try:
        s, info = env.reset(seed=seed)
        print("initial", json.dumps(snapshot(s), separators=(",", ":")))
        action = np.zeros(env.action_space.shape, dtype=np.float32)
        action[index] = value
        for t in range(steps):
            s, reward, term, trunc, info = env.step(action)
            print(t + 1, reward, term, trunc, json.dumps(snapshot(s), separators=(",", ":")))
            if term or trunc:
                break
    finally:
        env.close()


def effect_all(seed):
    for idx in range(11):
        env = make_env()
        try:
            s0, _ = env.reset(seed=seed)
            b = snapshot(s0)
            action = np.zeros(11, dtype=np.float32)
            action[idx] = 1.0 if idx == 10 else 0.2
            s1, reward, term, trunc, info = env.step(action)
            a = snapshot(s1)
            changed = {}
            for name in a:
                d = {k: round(v - b[name].get(k, v), 6) for k, v in a[name].items()
                     if isinstance(v, float) and abs(v - b[name].get(k, v)) > 1e-6}
                if d:
                    changed[name] = d
            print(idx, changed)
        finally:
            env.close()


def target_scan(seed, limit):
    """Coordinate sweeps around the tabletop-ready home posture."""
    env = make_env()
    try:
        s, _ = env.reset(seed=seed)
        target = snapshot(s)["target_block"]
        # Align the mobile base laterally with the target first.
        a = np.zeros(11, dtype=np.float32)
        a[1] = np.clip(target["pose_y"], -0.2, 0.2)
        a[10] = 1.0
        s, *_ = env.step(a)
        names = [n for n in s.get_object_names() if n != "robot"]
        home = np.array([0., -.35, -np.pi, -2.5, 0., -.87, np.pi / 2])
        # Most vertical tabletop motion is generated by shoulder/elbow/wrist pitch.
        candidates = []
        for bx in (-.12, -.22, -.32, -.42):
            for q2 in (-1.15, -.95, -.75, -.55, -.35, -.15, .05, .25):
                for q4 in (-3.1, -2.9, -2.7, -2.5, -2.3, -2.1, -1.9):
                    for q6 in (-1.47, -1.27, -1.07, -.87, -.67, -.47, -.27):
                        q = home.copy(); q[1] = q2; q[3] = q4; q[5] = q6
                        candidates.append((bx, q))
        # Nearby configurations first.
        candidates.sort(key=lambda z: abs(z[0] + .12) + np.sum(abs(z[1] - home)))
        t = 1
        for ci, (bx, q) in enumerate(candidates):
            robot = snapshot(s)["robot"]
            cur = np.array([robot[f"joint_{i}"] for i in range(1, 8)])
            # Move toward candidate, gripper open. Each delta is already legal.
            while max(abs(q - cur).max(), abs(bx - robot["pos_base_x"])) > .02:
                a = np.zeros(11, dtype=np.float32)
                a[0] = np.clip(bx - robot["pos_base_x"], -.2, .2)
                a[3:10] = np.clip(q - cur, -.2, .2)
                a[10] = 1.
                s, _, term, trunc, _ = env.step(a); t += 1
                robot = snapshot(s)["robot"]
                cur = np.array([robot[f"joint_{i}"] for i in range(1, 8)])
                if t >= limit or term or trunc: return print("LIMIT", t)
            a = np.zeros(11, dtype=np.float32); a[10] = -1.
            s, _, term, trunc, _ = env.step(a); t += 1
            snap = snapshot(s)
            moved = [n for n in names if snap[n]["grasp_active"] > .5]
            if snap["robot"]["grasp_active"] > .5 or moved:
                print("GRASP", "t", t, "candidate", ci, "bx", bx, "q", q.tolist(),
                      "held", moved, "robot", snap["robot"], "objects", {n:snap[n] for n in moved})
                return
            if t >= limit or term or trunc: return print("LIMIT", t)
        print("NO_GRASP", t)
    finally:
        env.close()


def full_place(seed):
    env = make_env()
    try:
        s, info = env.reset(seed=seed)
        start = snapshot(s)
        if any(n.startswith("obstruction") for n in start):
            print("WARNING obstructions present")
        def drive(q, grip):
            nonlocal s
            for _ in range(30):
                rob = snapshot(s)["robot"]
                cur = np.array([rob[f"joint_{i}"] for i in range(1, 8)])
                a = np.zeros(11, np.float32); a[3:10] = np.clip(q-cur, -.2, .2); a[10] = grip
                s, r, term, trunc, inf = env.step(a)
                if abs(q-cur).max() < .01 or term or trunc:
                    return r, term, trunc
            return r, term, trunc
        target = start["target_block"]
        qpick = ik(np.array([target[f"pose_{k}"] for k in "xyz"]), off=.16)
        drive(qpick, 1.)
        a = np.zeros(11, np.float32); a[10] = -1.; s, r, term, trunc, _ = env.step(a)
        print("PICK", snapshot(s)["robot"], qpick.tolist())
        if seed == 112:
            for gi in range(3):
                a = np.zeros(11, np.float32); a[10] = 1.
                s, r, term, trunc, _ = env.step(a)
                print("OPEN_AT_PICK", gi, snapshot(s)["robot"], snapshot(s)["target_block"])
            return
        region = start["target_region"]
        # Lift vertically before translating so the held block clears the table.
        rot = fk(qpick)[:3, :3]
        qlift = ik_fixed(np.array([target["pose_x"], target["pose_y"], .30]), qpick, rot)
        print("LIFT", drive(qlift, -1.), snapshot(s)["target_block"])
        if seed == 111:
            for gi in range(12):
                a = np.zeros(11, np.float32); a[3] = .05; a[10] = 1.
                s, r, term, trunc, _ = env.step(a)
                print("OPEN", gi, snapshot(s)["robot"]["finger_state"], snapshot(s)["robot"]["grasp_active"], snapshot(s)["target_block"]["grasp_active"])
            return
        qabove = ik_fixed(np.array([region["pose_x"], region["pose_y"], .30]), qlift, rot)
        print("ABOVE", drive(qabove, -1.), snapshot(s)["target_block"])
        qplace = qabove
        for zlevel in (.25, .20, .16, .135, .115, .110):
            xyz = np.array([region["pose_x"], region["pose_y"], zlevel])
            qplace = ik_fixed(xyz, qplace, rot)
            print("DESCEND", zlevel, drive(qplace, -1.), snapshot(s)["target_block"])
        a = np.zeros(11, np.float32); a[10] = 1.
        for _ in range(8):
            s, r, term, trunc, _ = env.step(a)
            if term or not snapshot(s)["robot"]["grasp_active"]: break
        print("DROP", r, term, trunc, "target", snapshot(s)["target_block"], "robot", snapshot(s)["robot"])
    finally:
        env.close()


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("mode", choices=("resets", "effects", "effect_all", "target_scan", "full_place"))
    p.add_argument("--n", type=int, default=20)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--index", type=int, default=0)
    p.add_argument("--value", type=float, default=0.2)
    p.add_argument("--steps", type=int, default=1)
    p.add_argument("--limit", type=int, default=280)
    a = p.parse_args()
    if a.mode == "resets":
        resets(a.n)
    elif a.mode == "effects":
        effects(a.seed, a.index, a.value, a.steps)
    elif a.mode == "effect_all":
        effect_all(a.seed)
    elif a.mode == "target_scan":
        target_scan(a.seed, a.limit)
    else:
        full_place(a.seed)
